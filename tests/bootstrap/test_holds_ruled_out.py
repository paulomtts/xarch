"""By the parts each breaks, in the profile's order, every file below the app that breaks one, by its path below the
app."""


def test_every_file_of_xarch_rules_out_the_parts_recorded_and_no_other():
    files = tuple((path.relative_to(APP).as_posix(), path.read_text(encoding="utf-8"))
                  for path in sorted(APP.rglob("*.py")))
    found = build_controllers().rules.holds(AskHolds(str(ROOT / "architecture.yaml"), "xarch", files, APP))
    assert isinstance(found, HoldsAsked)
    recorded = {path: parts for parts, paths in RULED_OUT.items() for path in paths}
    assert {held.path: held.breaks for held in found.files if held.breaks or held.path in recorded} == recorded
